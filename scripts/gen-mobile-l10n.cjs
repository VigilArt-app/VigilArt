const lookup = (obj, key) => key.split('.').reduce((a, p) => (a == null ? a : a[p]), obj);
const out = { en: { '@@locale': 'en' }, fr: { '@@locale': 'fr' } };

const add = (name, a, b) => {
  for (const [lang, raw] of [['en', a], ['fr', b]]) {
    const placeholders = {};
    const text = raw.replace(/\{\{(\w+)\}\}/g, (m, p) => {
      placeholders[p] = { type: p === 'count' || p === 'total' ? 'int' : 'String' };
      return `{${p}}`;
    });
    out[lang][name] = text;
    if (Object.keys(placeholders).length) out[lang][`@${name}`] = { placeholders };
  }
};

for (const [name, key] of Object.entries(WEB)) {
  const a = lookup(en, key);
  const b = lookup(fr, key);
  if (typeof a !== 'string' || typeof b !== 'string') {
    throw new Error(`Missing website translation: ${key}`);
  }
  add(name, a, b);
}
for (const [name, [a, b]] of Object.entries(MOBILE)) add(name, a, b);

const dir = path.join(root, 'mobile-app/lib/l10n/arb');
fs.mkdirSync(dir, { recursive: true });
for (const lang of ['en', 'fr']) {
  fs.writeFileSync(path.join(dir, `app_${lang}.arb`), JSON.stringify(out[lang], null, 2) + '\n');
}
